(function(root){
 'use strict';
 const node=typeof module!=='undefined'&&module.exports;
 const model=node?require('./data-model-storage.js'):root.TradeScopeDataStorage;
 const core=node?require('./monthly-source-contract.js'):root.TradeScopeMonthlySourceContract;
 const accountId='acc_lightfx_fx',cutover='2026-09',scope='lightfx-monthly-report';
 const rows=(m,e)=>m?.[e]?.records||[],decimal=v=>typeof v==='string'&&/^-?(?:0|[1-9]\d*)(?:\.\d+)?$/.test(v);
 const targets=Object.freeze([{component:'account',metric:'marketValue',label:'口座純資産観測'},
   {component:'account',metric:'unrealizedPnl',label:'価格評価損益（未決済swapを含まない）'}]);
 const matches=(s,t)=>s.component===t.component&&s.metric===t.metric&&s.currency==='JPY';
 const monthEnd=month=>new Date(Date.UTC(Number(month.slice(0,4)),Number(month.slice(5)),0)).toISOString().slice(0,10);
 function supportsSource(s,m){
   if(s.accountId!==accountId||!targets.some(t=>matches(s,t))||s.asOf!==monthEnd(s.targetMonth))return false;
   if(!s.reference)return s.sourceType==='manual';
   const ref=s.reference,record=rows(m,ref.entity).find(r=>r.id===ref.id);
   const snapshot=ref.entity==='accountSnapshots'?record:rows(m,'accountSnapshots').find(r=>r.id===record?.adoptedAccountSnapshotId);
   const batch=rows(m,'importBatches').find(b=>b.id===snapshot?.importBatchId);
   // New revisions reference immutable Snapshots. Released Input/State references
   // remain readable, but are never generated by this broker hook.
   return s.sourceType==='pdf'&&ref.sourceScope===scope&&snapshot?.sourceScope===scope&&snapshot.sourceMode==='imported'
     &&snapshot.observationType==='officialMonthEnd'&&snapshot.valuationCurrency==='JPY'&&batch?.sourceProvider==='lightfx'
     &&batch.sourceType==='pdf'&&(['accountSnapshots'].includes(ref.entity)?ref.field===(s.metric==='marketValue'?'netAssetValue':'unrealizedPnl')
       :['monthlyAccountInputs','monthlyAccountStates'].includes(ref.entity)&&s.metric==='unrealizedPnl'&&ref.field==='sourceValues.unrealizedPnl');
 }
 function resolve(m,targetMonth,{validate=true}={}){
   if(validate)model.validateModels(m);
   if(!/^\d{4}-(?:0[1-9]|1[0-2])$/.test(targetMonth))throw Error('INVALID_LIGHT_SCALAR_MONTH');
   if(targetMonth<cutover)return null;
   const inputs=rows(m,'monthlyAccountInputs').filter(r=>r.accountId===accountId&&r.targetMonth===targetMonth);
   const states=rows(m,'monthlyAccountStates').filter(r=>r.accountId===accountId&&r.targetMonth===targetMonth);
   const selection=states[0]??inputs[0],snapshot=rows(m,'accountSnapshots').find(r=>r.id===selection?.adoptedAccountSnapshotId);
   const all=core.candidates(m,{accountId,targetMonth}),heads=core.heads(rows(m,'monthlySources')).filter(r=>r.accountId===accountId&&r.targetMonth===targetMonth);
   // An old position subtotal is NOT an additional account observation. Respect
   // existing audit records by blocking the overlap; never delete or subtract it.
   const scopeConflict=heads.some(h=>h.currency==='JPY'&&['marketValue','unrealizedPnl','holdings'].includes(h.metric)
     &&!targets.some(t=>matches(h,t)))||heads.some(h=>matches(h,targets[0]))&&heads.some(h=>h.metric==='cashBalance'&&h.currency==='JPY');
   const nativeConflict=inputs.length>1||states.length>1;
   const metrics=targets.map(t=>{
     const query=core.descriptor({accountId,targetMonth,component:t.component,asOf:null},t.metric,null);
     const decisions=heads.filter(h=>matches(h,t));let r;
     if(decisions.length)r=core.resolve(m,query);
     else{
       const source=snapshot?all.find(c=>matches(c,t)&&c.reference?.entity==='accountSnapshots'&&c.reference.id===snapshot.id):null;
       const value=t.metric==='unrealizedPnl'?(inputs[0]?.adoptedValues?.unrealizedPnl??selection?.adoptedUnrealizedPnl??snapshot?.unrealizedPnl??null):snapshot?.netAssetValue??null;
       r={source,value,status:nativeConflict?'conflict':source?'compatibility':'missing'};
     }
     if(scopeConflict||r.source&&!supportsSource(r.source,m))r={...r,status:'conflict',value:null};
     let rawValue=null;try{rawValue=r.source?core.sourceValue(r.source,m):null;}catch(_){r={...r,status:'stale',value:null};}
     const value=r.value??null,source=r.source??null;
     return {...t,currency:'JPY',query,...r,value,rawValue,source,hasCommon:decisions.length>0,
       hasOverride:!!source&&(value===null||rawValue===null?value!==rawValue:!model.equalDecimal(value,rawValue)),
       sourceMonth:source?.targetMonth??null,snapshotAsOf:source?.asOf??null,
       blocked:['conflict','stale','unresolved'].includes(r.status)};
   });
   const asset=metrics[0],pnl=metrics[1];
   return {accountId,targetMonth,metrics,scopeConflict,hasCommon:scopeConflict||metrics.some(r=>r.hasCommon),
     hasData:metrics.some(r=>r.source||r.hasCommon),blocked:metrics.some(r=>r.blocked),whole:null,
     observedAsset:decimal(asset.value)?asset.value:null,unrealizedPnl:decimal(pnl.value)?pnl.value:null,
     components:[{key:'account',name:'口座観測',asset:asset.value,unrealized:pnl.value,id:asset.source?.reference?.id??asset.source?.id??null,
       snapshotAsOf:asset.snapshotAsOf,blocked:asset.blocked,source:{revisionId:asset.source?.id??null,adoptionId:asset.adoption?.id??null,sourceType:asset.source?.sourceType??null}}]};
 }
 function candidateOperation(m,targetMonth,snapshotId,{required=true}={}){
   const sources=core.candidates(m,{accountId,targetMonth}).filter(c=>!c.registered&&targets.some(t=>matches(c,t))
     &&c.reference?.entity==='accountSnapshots'&&c.reference.id===snapshotId&&supportsSource(c,m));
   if(required&&sources.length!==2)throw Error('LIGHT_SCALAR_CANDIDATE_PLAN_INVALID');return {sources};
 }
 const api=Object.freeze({accountId,cutover,targets,resolve,supportsSource,candidateOperation});
 if(node)module.exports=api;else root.TradeScopeLightScalarAdoption=api;
})(typeof globalThis!=='undefined'?globalThis:this);
